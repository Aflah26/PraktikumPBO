
public class tugas1 {
    public static void main(String[] args) {
        int x = 10;
        int y = 10;

        System.out.println("Nilai awal x = 10, y = 10");
        
        
        System.out.println("x++ menghasilkan: " + (x++)); 
        System.out.println("Nilai x sekarang: " + x);     

        
        System.out.println("++y menghasilkan: " + (++y)); 
        System.out.println("Nilai y sekarang: " + y);     
    }
}
    

