package TugasP5;

public class Tugas7 {
    public static void main(String[] args) {

        int i = 1;

        System.out.println("Menggunakan i++:");

        while (i <= 3) {
            System.out.println(i++);
        }

        i = 1;

        System.out.println("Menggunakan ++i:");

        while (i <= 3) {
            System.out.println(++i);
        }
    }
}